def owner_approval_node(state):

    print("\n" + "=" * 55)
    print("WAITING FOR BUSINESS OWNER APPROVAL")
    print("=" * 55)

   
    report_file = (
        data_folder / "marketing_agent_gemini_campaigns.md"
    )

    if report_file.exists():

        campaign_report = report_file.read_text(
            encoding="utf-8"
        )

    else:

        campaign_report = "Marketing campaign report not found."

    
    approval_request = {
        "title": "Growth360 Campaign Approval",
        "business_strategy": state.get(
            "marketing_strategy",
            "OWNER REVIEW REQUIRED"
        ),
        "campaign_report": campaign_report,
        "message": (
            "Please review the generated marketing campaigns. "
            "Do you approve these campaign plans?"
        ),
        "available_decisions": [
            "approve",
            "reject"
        ]
    }

   
    owner_decision = interrupt(approval_request)

    
    decision = str(owner_decision).strip().lower()

    if decision in ["approve", "approved", "yes"]:

        approval_status = "APPROVED_FOR_NEXT_STEP"

        print("\nOwner approved the campaign plans.")

    else:

        approval_status = "REJECTED_NEEDS_REVISION"

        print("\nOwner rejected the campaign plans.")

    return {
        "owner_approval": approval_status,
        "agent_outputs": [
            f"Owner Approval: {approval_status}"
        ]
    }




workflow = StateGraph(Growth360State)


workflow.add_node("review", review_node)
workflow.add_node("demand", demand_node)
workflow.add_node("doctor", doctor_node)

workflow.add_node("gemini_doctor", gemini_doctor_node)

workflow.add_node("improvement_first", improvement_first_node)
workflow.add_node("growth_first", growth_first_node)
workflow.add_node("owner_review", owner_review_node)

workflow.add_node("marketing", marketing_node)
workflow.add_node("gemini_marketing", gemini_marketing_node)
workflow.add_node("owner_approval", owner_approval_node)




workflow.add_edge(START, "review")

workflow.add_edge("review", "demand")

workflow.add_edge("demand", "doctor")

workflow.add_edge("doctor", "gemini_doctor")

workflow.add_edge(START, "review")

workflow.add_edge("review", "demand")

workflow.add_edge("demand", "doctor")

workflow.add_edge("doctor", "gemini_doctor")



workflow.add_conditional_edges(
    "gemini_doctor",
    choose_marketing_route,
    {
        "improvement_first": "improvement_first",
        "growth_first": "growth_first",
        "owner_review": "owner_review"
    }
)



workflow.add_edge("improvement_first", "marketing")

workflow.add_edge("growth_first", "marketing")

workflow.add_edge("owner_review", "marketing")


workflow.add_edge("marketing", "gemini_marketing")

workflow.add_edge("gemini_marketing", END)

workflow.add_edge("marketing", "gemini_marketing")

workflow.add_edge(
    "gemini_marketing",
    "owner_approval"
)

workflow.add_edge(
    "owner_approval",
    END
)



checkpointer = InMemorySaver()

growth360_graph = workflow.compile(
    checkpointer=checkpointer
)







if __name__ == "__main__":

    print("\nGROWTH360 INTELLIGENT AI WORKFLOW STARTED")
    print("=" * 55)

    initial_state = {
        "completed_agents": [],
        "agent_outputs": [],
        "business_evidence": {},
        "business_doctor_report": "",
        "marketing_strategy": "",
        "routing_reason": "",
        "owner_approval": "PENDING"
    }

    # Give this workflow execution a unique ID
    config = {
        "configurable": {
            "thread_id": "growth360-cafe-nova-demo"
        }
    }

    # Start the workflow with checkpointing
    result = growth360_graph.invoke(
        initial_state,
        config=config
    )

    # Check whether the workflow is waiting for approval
    if result.get("__interrupt__"):

        print("\n" + "=" * 55)
        print("CAMPAIGN PLANS REQUIRE OWNER APPROVAL")
        print("=" * 55)

        pending = result["__interrupt__"][0]

        print(pending.value)

        # Ask the owner for a decision
        while True:

            decision = input(
                "\nEnter your decision (approve/reject): "
            ).strip().lower()

            if decision in ["approve", "reject"]:
                break

            print("Please enter only approve or reject.")

        # Resume using the SAME thread ID
        final_state = growth360_graph.invoke(
            Command(resume=decision),
            config=config
        )

    else:

        final_state = result

    # Display final workflow results
    print("\n" + "=" * 55)
    print("GROWTH360 WORKFLOW COMPLETED!")
    print("=" * 55)

    print("\nAGENTS COMPLETED:")

    for agent in final_state["completed_agents"]:
        print(f"[SUCCESS] {agent}")

    print(
        "\nTotal agent outputs stored:",
        len(final_state["agent_outputs"])
    )

    print(
        "Total business reports shared:",
        len(final_state["business_evidence"])
    )

    print(
        "\nOWNER APPROVAL STATUS:",
        final_state["owner_approval"]
    )

    print("\nGrowth360 workflow finished.")
