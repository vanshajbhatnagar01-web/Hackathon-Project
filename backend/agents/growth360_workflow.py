def load_business_evidence():
    """
    Read the reports generated by the Python agents
    and convert them into dictionaries.

    LangGraph will store this information in shared state.
    """

    report_files = [

        
        "business_health_score.csv",
        "business_health_breakdown.csv",
        "business_doctor_diagnosis.csv",
        "cleaned_business_profile.csv",

      
        "review_agent_sentiment_summary.csv",
        "review_agent_theme_report.csv",
        "review_agent_product_complaints.csv",
        "review_agent_insights.csv",

       
        "demand_agent_product_report.csv",
        "demand_agent_hourly_report.csv",
        "demand_agent_daily_report.csv",
        "demand_agent_insights.csv",

       
        "seven_day_demand_forecast.csv",
        "root_cause_findings.csv",
        "root_cause_product_analysis.csv"
    ]

    business_evidence = {}

    for file_name in report_files:

        file_path = data_folder / file_name

        if not file_path.exists():
            print(f"Report not found: {file_name}")
            continue

        try:

            data = pd.read_csv(file_path)

            
            data = data.head(10)

            
            data = data.astype(object).where(
                pd.notna(data),
                None
            )

            
            business_evidence[file_name] = (
                data.to_dict(orient="records")
            )

        except Exception as error:

            print(f"Could not load {file_name}: {error}")

    print(
        f"\nLoaded {len(business_evidence)} business reports "
        "into shared state."
    )

    return business_evidence


def convert_to_number(value):

    try:
        return float(
            str(value)
            .replace(",", "")
            .replace("%", "")
            .strip()
        )

    except (ValueError, TypeError):
        return None


def extract_health_score(evidence):
    """
    Extract the overall business health score
    from business_health_score.csv.
    """

    rows = evidence.get("business_health_score.csv", [])

    preferred_keys = [
        "business_health_score",
        "overall_health_score",
        "health_score",
        "overall_score"
    ]

    for row in rows:

        
        for key, value in row.items():

            key_name = key.lower().replace(" ", "_")

            if key_name in preferred_keys:

                number = convert_to_number(value)

                if number is not None:
                    return number

        
        row_text = " ".join(
            str(value) for value in row.values()
        ).lower()

        if "business health" in row_text or "overall health" in row_text:

            for key, value in row.items():

                if key.lower() in ["score", "value", "result"]:

                    number = convert_to_number(value)

                    if number is not None:
                        return number

   
    if len(rows) == 1:

        for key, value in rows[0].items():

            if "score" in key.lower():

                number = convert_to_number(value)

                if number is not None:
                    return number

    return None



def extract_negative_percentage(evidence):
    """
    Calculate negative review percentage using
    the sentiment and count columns.
    """

    rows = evidence.get(
        "review_agent_sentiment_summary.csv", []
    )

    if not rows:
        return None

    negative_count = None
    total_count = 0

    for row in rows:

        sentiment = str(
            row.get("sentiment", "")
        ).strip().lower()

        count = convert_to_number(
            row.get("count")
        )

        if count is None:
            continue

        total_count += count

        if sentiment == "negative":
            negative_count = count

    if (
        negative_count is None
        or total_count <= 0
    ):
        return None

    negative_percentage = (
        negative_count / total_count
    ) * 100

    return negative_percentage





def get_marketing_decision(state):

    evidence = state.get("business_evidence", {})

    health_score = extract_health_score(evidence)

    negative_percentage = extract_negative_percentage(
        evidence
    )

    print("\nBUSINESS DECISION ANALYSIS")
    print("-" * 45)

    print("Health Score:", health_score)

    print(
        "Negative Review Percentage:",
        negative_percentage
    )

    
    if (
        health_score is None
        or negative_percentage is None
    ):

        return (
            "owner_review",
            "OWNER REVIEW REQUIRED",
            "Required business metrics could not be extracted."
        )

    
    if (
        health_score < 65
        or negative_percentage >= 15
    ):

        return (
            "improvement_first",
            "IMPROVEMENT FIRST",
            (
                f"Health score is {health_score}/100 "
                f"and negative reviews are {negative_percentage:.2f}%. "
                "The business should address operational and "
                "customer experience problems before aggressive growth."
            )
        )

    
    return (
        "growth_first",
        "GROWTH FIRST",
        (
            f"Health score is {health_score}/100 "
            f"and negative reviews are {negative_percentage:.2f}%. "
            "The business meets the configured thresholds "
            "for prioritizing growth opportunities."
        )
    )




