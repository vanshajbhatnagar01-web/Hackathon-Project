def gemini_doctor_node(state):

    print("\n" + "=" * 55)
    print("Running Gemini Business Doctor")
    print("=" * 55)

    shared_evidence = state.get("business_evidence", {})

    try:

        response = generate_business_diagnosis(
            shared_evidence
        )

        agent_name = "Gemini Business Doctor"

    except Exception as error:

        print("\nGemini Business Doctor unavailable.")
        print("Reason:", error)

        print("\nUsing Python Business Doctor fallback.")

        response = create_rule_based_fallback(
            "business_doctor_diagnosis.csv",
            "BUSINESS DOCTOR FALLBACK REPORT"
        )

        
        fallback_path = (
            data_folder / "business_doctor_gemini_report.md"
        )

        fallback_path.write_text(
            response,
            encoding="utf-8"
        )

        agent_name = "Business Doctor [RULE-BASED FALLBACK]"

    return {
        "completed_agents": [agent_name],

        "agent_outputs": [
            f"{agent_name}:\n{response}"
        ],

        "business_doctor_report": response
    }



def create_rule_based_fallback(csv_file, report_title):
    """
    Create a clearly labelled fallback report
    using the existing Python agent's CSV output.
    """

    report_path = data_folder / csv_file

    if not report_path.exists():
        return (
            f"# {report_title}\n\n"
            "Gemini was unavailable and the Python fallback "
            "report could not be found."
        )

    data = pd.read_csv(report_path)

    if data.empty:
        return (
            f"# {report_title}\n\n"
            "The Python fallback report is empty."
        )

    report = f"""
# {report_title}

**Source:** Python rule-based agent fallback.

**Notice:** Gemini was unavailable during this run.
This report was generated from the existing Python agent
results, not by Gemini.

## Available Business Findings

{data.to_string(index=False)}
"""

    return report





